	ORG 00H
	AJMP INIT

	ORG 03H
	AJMP DETECTED_IR_SIGNAL

	ORG 50H

CHARACTER_TABLE:
	;別 
	DB 0FFH,07FH,0C1H,0BFH,0DDH,0CFH,05DH,0F0H 
	DB 0DDH,0BDH,0DDH,07DH,0DDH,0BDH,0C1H,0C1H 
	DB 0FFH,0FFH,0FFH,0FFH,007H,0F0H,0FFH,0BFH 
	DB 0FFH,07FH,000H,080H,0FFH,0FFH,0FFH,0FFH 
	;當 
	DB 0DFH,0FFH,0E7H,0FFH,0F7H,003H,015H,0AAH 
	DB 0D3H,0AAH,0D7H,0AAH,0D7H,0AAH,0D0H,082H 
	DB 0D7H,0AAH,0D7H,0AAH,0D3H,0AAH,015H,0AAH 
	DB 0F7H,003H,0D7H,0FFH,0E7H,0FFH,0FFH,0FFH 
	;我 
	DB 0DFH,0FFH,0DBH,0F7H,0DBH,0B7H,0DBH,07BH 
	DB 001H,080H,0DCH,0FDH,0DDH,0BEH,0DFH,0BFH 
	DB 0DFH,0DFH,000H,0ECH,0DFH,0F3H,0DDH,0EBH 
	DB 0D3H,0DDH,05FH,0BEH,0DFH,007H,0FFH,0FFH 

INIT:
	MOV TMOD, #01H
	MOV DPTR, #CHARACTER_TABLE
	MOV P0, #0FFH
	MOV P1, #0FFH
	MOV P2, #0FFH
	MOV 0C0H, #0FFH

	MOV R2, #030H

	MOV IE, #10000001B   ; EA=1, EX0=1
    MOV TCON, #00000001B ; IT0=1 

LOOP:
	ACALL SETCENTERLED
	JMP LOOP

SETCENTERLED:
	MOV P0, #00H
	MOV P1, #0FFH
	RET
	
DETECTED_IR_SIGNAL:
	MOV P0, #0FFH	
	MOV P1, #00H
	ACALL DISPLAY
	RETI

DISPLAY:
DISPLAY_INIT:
	MOV DPTR, #CHARACTER_TABLE
	MOV R2, #030H

DISPLAY_MAIN:
	CLR A
	MOVC A, @A+DPTR
	MOV P2, A
	INC DPTR
	
	CLR A
	MOVC A, @A+DPTR
	MOV 0C0H, A
	INC DPTR
	ACALL DELAY25muS
	DJNZ R2, DISPLAY_MAIN
	
	MOV P2, #0FFH
	MOV 0C0H, #0FFH
	RET

DELAY25muS:
	MOV TH0, #0FEH
	MOV TL0, #0F7H
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET
	END
