	ORG 00H
	AJMP INIT

	ORG 0BH
	AJMP TIMER0_ISR

	ORG 23H
	AJMP SERIAL_ISR

	ORG 50H


INIT:
	MOV TMOD, #00100001B ;timer1 mode2, timer0 mode1
	MOV SCON, #01010000B ;serial mode1, REN enabled
	MOV IE,   #10010010B ;enable global, serial interrupt and timer0 interrupt
	ORL PCON,#10000000B  ;SETTING PCON.7 SMOD 1 BAUD RATE =FORCS/32 TI
	MOV TH1,#0F3H
	MOV TL1,#0F3H

	MOV R2, #00H  ;Buzzer Enable Flag
	MOV R3, #00H  ;TH1
	MOV R4, #00H  ;TL1
	MOV P0, #00H  ;Buzzer Output

	SETB TR1 ;start timer1

LOOP:
	CJNE R2, #01H, LOOP
	CLR TR0
	CLR TR1
	MOV TMOD, #00010001B ;timer1 mode1, timer0 mode1
	MOV R6, #04H
	MOV R7, #0FAH
	SETB TR0 ;start timer0
	ACALL DELAY1S
	
	CLR TR0
	CLR TR1
	MOV TMOD, #00100001B ;timer1 mode2, timer0 mode1
	MOV TH1, #0F3H       ;4800 baud rate
	MOV TL1, #0F3H
	SETB TR1
	MOV R2, #00H
	JMP LOOP

TIMER0_ISR:
	PUSH  ACC
	CLR   TR0
	MOV   TH0, R3
	MOV   TL0, R4
	MOV   A, P0
	CPL   A
	MOV   P0, A
	SETB  TR0
	POP   ACC
	RETI

SERIAL_ISR:
	PUSH ACC
	JB RI, RECEIVE_CHAR
	JB TI, TRANSMIT_CHAR
	CLR RI
	CLR TI
	JMP EXIT_ISR

RECEIVE_CHAR:
	MOV A, SBUF
	ACALL BUZZER_CHOOSE_FREQ
	CLR RI
	JMP EXIT_ISR

TRANSMIT_CHAR:
	CLR TI
	JMP EXIT_ISR

EXIT_ISR:
	POP ACC
	RETI

BUZZER_CHOOSE_FREQ:
BUZZER_D0:
	CJNE A, #031H, BUZZER_RE
		MOV R3, #0FCH
		MOV R4, #08FH
		MOV R2, #01H
		RET

BUZZER_RE:
	CJNE A, #032H, BUZZER_MI
		MOV R3, #0FCH
		MOV R4, #0EFH
		MOV R2, #01H
		RET

BUZZER_MI:
	CJNE A, #033H, BUZZER_FA
		MOV R3, #0FDH
		MOV R4, #045H
		MOV R2, #01H
		RET

BUZZER_FA:
	CJNE A, #034H, BUZZER_SO
		MOV R3, #0FDH
		MOV R4, #06CH
		MOV R2, #01H
		RET

BUZZER_SO:
	CJNE A, #035H, BUZZER_LA
		MOV R3, #0FDH
		MOV R4, #0B4H
		MOV R2, #01H
		RET

BUZZER_LA:
	CJNE A, #036H, BUZZER_SI
		MOV R3, #0FDH
		MOV R4, #0F4H
		MOV R2, #01H
		RET

BUZZER_SI:
	CJNE A, #037H, DEFAULT_NOSOUND
		MOV R3, #0FEH
		MOV R4, #02EH
		MOV R2, #01H
		RET

DEFAULT_NOSOUND:
	MOV R2, #00H
	MOV P0, #00H
	RET
	
DELAY1S:
	MOV TH1, #0FCH
	MOV TL1, #018H
	SETB TR1	

WAIT:
	JNB TF1, $
	CLR TR1
	CLR TF1
	DJNZ R6, DELAY1S
	MOV R6, #04H
	DJNZ R7, DELAY1S
	RET
	END
