	ORG 00H
	AJMP INIT

	ORG 23H
	AJMP SERIAL_ISR

	ORG 50H


INIT:
	MOV TMOD, #00100001B ;timer1 mode2, timer0 mode1
	MOV SCON, #01010000B ;serial mode1, REN enabled
	MOV IE,   #10010000B ;enable global, serial interrupt
	ORL PCON,#10000000B ;SETTING PCON.7 SMOD 1 BAUD RATE =FORCS/32 TI
	MOV TH1,#0F3H
	MOV TL1,#0F3H
	SETB TR1 ;start timer1

LOOP:
	JMP LOOP

SERIAL_ISR:
	PUSH ACC
	JB RI, RECEIVE_CHAR
	JB TI, TRANSMIT_CHAR
	CLR RI
	CLR TI
	JMP EXIT_ISR

RECEIVE_CHAR:
	MOV A, SBUF
	ADD A, #020H
	CLR RI
	MOV SBUF, A
	JMP EXIT_ISR

TRANSMIT_CHAR:
	CLR TI
	JMP EXIT_ISR

EXIT_ISR:
	POP ACC
	RETI
