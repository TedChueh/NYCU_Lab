	ORG 00H
	AJMP INIT

	ORG 0BH
	AJMP TIMER0_ISR

	ORG 23H
	AJMP SERIAL_ISR

	ORG 50H

MODE3_TABLE:
	DB 07H
	DB 01H
	DB 06H
	DB 02H
	DB 05H
	DB 03H
	DB 04H

INIT:
	MOV DPTR, #MODE3_TABLE
	MOV TMOD, #00100001B ;timer1 mode2, timer0 mode1
	MOV SCON, #01010000B ;serial mode1, REN enabled
	MOV IE,   #10010010B ;enable global, serial interrupt and timer0 interrupt
	ORL PCON,#10000000B  ;SETTING PCON.7 SMOD 1 BAUD RATE =FORCS/32 TI
	MOV TH1,#0F3H
	MOV TL1,#0F3H
	
	MOV R1, #00H  ;Sequence Temporary Register
	MOV R2, #00H  ;Buzzer Mode Flag
	MOV R3, #00H  ;TH1
	MOV R4, #00H  ;TL1
	MOV P0, #00H  ;Buzzer Output

	SETB TR1 ;start timer1

LOOP:
	ACALL SELECT_MODE
	JMP LOOP

SELECT_MODE:
SELECT_MODE1:
	CJNE R2, #01H, SELECT_MODE2
BUZZ_MODE1_INIT:
	ACALL TIMER1_MODE1
	MOV A, #07H
BUZZ_MODE1_MAIN:
	ACALL BUZZER_CHOOSE_FREQ
	MOV R6, #02H
	MOV R7, #0FAH
	SETB TR0
	ACALL DELAY500ms
	DEC A
	CJNE A, #00H, BUZZ_MODE1_MAIN
	ACALL TIMER1_MODE2
	JMP DEFAULT

SELECT_MODE2:
	CJNE R2, #02H, SELECT_MODE3
BUZZ_MODE2_INIT:
	ACALL TIMER1_MODE1
	MOV A,  #01H
BUZZ_MODE2_MAIN:
	ACALL BUZZER_CHOOSE_FREQ
	MOV R6, #02H
	MOV R7, #0FAH
	SETB TR0
	ACALL DELAY500ms
	INC A
	CJNE A, #08H, BUZZ_MODE2_MAIN
	ACALL TIMER1_MODE2
	JMP DEFAULT

SELECT_MODE3:
	CJNE R2, #03H, DEFAULT
BUZZ_MODE3_INIT:
	ACALL TIMER1_MODE1
	MOV A,  #01H
BUZZ_MODE3_MAIN:
	MOV R1, A
	MOVC A, @A+DPTR
	ACALL BUZZER_CHOOSE_FREQ
	MOV R6, #02H
	MOV R7, #0FAH
	SETB TR0
	ACALL DELAY500ms
	MOV A, R1
	INC A
	CJNE A, #08H, BUZZ_MODE3_MAIN
	ACALL TIMER1_MODE2
	JMP DEFAULT

DEFAULT:
	MOV R2, #00H
	RET

TIMER1_MODE1:
	CLR TR0
	CLR TR1
	MOV TMOD, #00010001B ;timer1 mode1, timer0 mode1
	RET

TIMER1_MODE2:
	CLR TR0
	CLR TR1
	MOV TMOD, #00100001B ;timer1 mode2, timer0 mode1
	MOV TH1, #0F3H       ;4800 baud rate
	MOV TL1, #0F3H
	SETB TR1
	RET

TIMER0_ISR:
	PUSH  ACC
	CLR   TR0
	MOV   TH0, R3
	MOV   TL0, R4
	MOV   A, P0
	CPL   A
	MOV   P0, A
	SETB  TR0
	POP   ACC
	RETI

SERIAL_ISR:
	PUSH ACC
	JB RI, RECEIVE_CHAR
	JB TI, TRANSMIT_CHAR
	CLR RI
	CLR TI
	JMP EXIT_ISR

RECEIVE_CHAR:
	MOV A, SBUF
	ACALL CHOOSE_MODE
	CLR RI
	JMP EXIT_ISR

TRANSMIT_CHAR:
	CLR TI
	JMP EXIT_ISR

EXIT_ISR:
	POP ACC
	RETI

CHOOSE_MODE:
CHOOSE_MODE1:
	CJNE A, #031H, CHOOSE_MODE2
	MOV R2, #01H
	RET

CHOOSE_MODE2:
	CJNE A, #032H, CHOOSE_MODE3
	MOV R2, #02H
	RET

CHOOSE_MODE3:
	CJNE A, #033H, NO_CHOICE
	MOV R2, #03H
	RET

NO_CHOICE:
	MOV R2, #00H
	RET

BUZZER_CHOOSE_FREQ:
BUZZER_D0:
	CJNE A, #01H, BUZZER_RE
		MOV R3, #0FCH
		MOV R4, #08FH
		RET

BUZZER_RE:
	CJNE A, #02H, BUZZER_MI
		MOV R3, #0FCH
		MOV R4, #0EFH
		RET

BUZZER_MI:
	CJNE A, #03H, BUZZER_FA
		MOV R3, #0FDH
		MOV R4, #045H
		RET

BUZZER_FA:
	CJNE A, #04H, BUZZER_SO
		MOV R3, #0FDH
		MOV R4, #06CH
		RET

BUZZER_SO:
	CJNE A, #05H, BUZZER_LA
		MOV R3, #0FDH
		MOV R4, #0B4H
		RET

BUZZER_LA:
	CJNE A, #06H, BUZZER_SI
		MOV R3, #0FDH
		MOV R4, #0F4H
		RET

BUZZER_SI:
	CJNE A, #07H, DEFAULT_NOSOUND
		MOV R3, #0FEH
		MOV R4, #02EH
		RET

DEFAULT_NOSOUND:
	MOV P0, #00H
	RET
	
DELAY500ms:
	MOV TH1, #0FCH
	MOV TL1, #018H
	SETB TR1	

WAIT:
	JNB TF1, $
	CLR TR1
	CLR TF1
	DJNZ R6, DELAY500ms
	MOV R6, #02H
	DJNZ R7, DELAY500ms
	RET
	END
