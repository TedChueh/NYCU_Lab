	ORG 00H
	AJMP INIT
	ORG 50H

KEYPAD:
	DB 00H
	DB 04H  
	DB 08H 
	DB 0CH  

	DB 01H  
	DB 05H  
	DB 09H   
	DB 0DH

	DB 02H  
	DB 06H  
	DB 0AH
	DB 0EH

	DB 03H   
	DB 07H  
	DB 0BH  
	DB 0FH

	DB 010H ; No key pressed

INIT:
    MOV TMOD, #01H 
	MOV 94H, #0FFH
	MOV R0, #010H ; Col Detection
	MOV R1, #00H  ; Row Detection

	MOV R2, #00H ;Temp For Row Detection
	MOV R3, #00H ; Motor Target Degree(Null)
	MOV R4, #00H ; For Loop Variable
	MOV R5, #04H ; Motor Number of Shift to achieve 1 Turn

	MOV R6, #00H ; Motor Ouput For 1-2 Phase Shifting
	MOV R7, #00H ; Motor Ouput For 1-2 Phase Shifting

	MOV P0, #0FFH ; Keypad Input
    MOV P1, #00010001B  ; Motor Output

LOOP:
	ACALL DETECT
	ACALL EXECUTE
	JMP LOOP

;KEYPAD DETECT CONTROL
DETECT:
	MOV R0, #010H
	MOV R1, #00H

DETECTCOL0:
    MOV P0, #07FH
	ACALL DELAY10MS
	MOV A, P0
    ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
    JZ DETECTCOL1
	MOV R0, #00H
	ACALL DETECTROW
	RET

DETECTCOL1:
	MOV P0, #0BFH
	ACALL DELAY10MS
	MOV A, P0
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DETECTCOL2
	MOV R0, #04H
	ACALL DETECTROW
	RET

DETECTCOL2:
	MOV P0, #0DFH
	ACALL DELAY10MS
	MOV A, P0
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DETECTCOL3	
	MOV R0, #08H
	ACALL DETECTROW
	RET

DETECTCOL3:
	MOV P0, #0EFH
	ACALL DELAY10MS
	MOV A, P0
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DEFAULT_NOPRESSED
	MOV R0, #0CH
	ACALL DETECTROW
	RET

DEFAULT_NOPRESSED:
	RET

DETECTROW:
	CJNE R2, #0EH,  NOTPRESSEDROW0
	MOV R1, #00H
	RET

NOTPRESSEDROW0:
	CJNE R2, #0DH,  NOTPRESSEDROW1
	MOV R1, #01H
	RET

NOTPRESSEDROW1:
	CJNE R2, #0BH,  NOTPRESSEDROW2
	MOV R1, #02H
	RET

NOTPRESSEDROW2:
	CJNE R2, #07H,  DEFAULT
	MOV R1, #03H
	RET

DEFAULT:
	RET

