	ORG 00H
	AJMP INIT
	ORG 50H

INIT:
    MOV TMOD, #01H 
    MOV P1, #00010001B ; Motor Output Pin
	MOV R3, #05AH ; Motor Target Degree(90)
	MOV R4, #04H ; Motor 1 Cycle Step(4)
	MOV R5, #06H ; Motor Number of Cycle to achieve 1 Degree(6)

LOOP:
	ACALL MOTOR_CCW_DEG90
	ACALL MOTOR_CW_DEG90
	ACALL MOTOR_CW_DEG90
	AJMP $

MOTOR_CW_DEG90:
MOTOR_CW_DEG90_INIT:
	MOV R3, #046H
MOTOR_CW_DEG90_MAIN:
	ACALL MOTOR_CW_DEG1
	DJNZ R3, MOTOR_CW_DEG90_MAIN
	RET

MOTOR_CCW_DEG90:
MOTOR_CCW_DEG90_INIT:
	MOV R3, #046H
MOTOR_CCW_DEG90_MAIN:
	ACALL MOTOR_CCW_DEG1
	DJNZ R3, MOTOR_CCW_DEG90_MAIN
	RET

MOTOR_CW_DEG1:
MOTOR_CW_DEG1_INIT:
	MOV R4, #04H
	MOV R5, #01H
MOTOR_CW_DEG1_MAIN:
	ACALL DELAY5MS
	MOV A, P1
	RR A
	MOV P1, A
	DJNZ R4, MOTOR_CW_DEG1_MAIN
	MOV R4, #04H
	DJNZ R5, MOTOR_CW_DEG1_MAIN
	RET

MOTOR_CCW_DEG1:
MOTOR_CCW_DEG1_INIT:
	MOV R4, #04H
	MOV R5, #01H
MOTOR_CCW_DEG1_MAIN:
	ACALL DELAY5MS
	MOV A, P1
	RL A
	MOV P1, A
	DJNZ R4, MOTOR_CCW_DEG1_MAIN
	MOV R4, #04H
	DJNZ R5, MOTOR_CCW_DEG1_MAIN
	RET

DELAY5MS:
	MOV TH0, #0ECH    
	MOV TL0, #078H   
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET
	END