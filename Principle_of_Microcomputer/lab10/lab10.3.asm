	ORG 00H
	AJMP INIT

	ORG 0BH
	AJMP RESET_TIMER0

	ORG 01BH
	AJMP RESET_TIMER1
	
	ORG 50H

RHYTHM_DATA:
    DB  0D8H,0F0H
    DB  0ECH,078H
    DB  0D8H,0F0H
    DB  0ECH,078H
    DB  0D8H,0F0H
    DB  0D8H,0F0H

    DB  0D8H,0F0H
    DB  0ECH,078H
    DB  0D8H,0F0H
    DB  0ECH,078H
    DB  0D8H,0F0H
    DB  0D8H,0F0H

    DB  0D8H,0F0H
    DB  0D8H,0F0H
    DB  0D8H,0F0H
    DB  0D8H,0F0H
    DB  0D8H,0F0H
    DB  0ECH,078H
    DB  0D8H,0F0H
    DB  0ECH,078H
    DB  0D8H,0F0H
    DB  0D8H,0F0H


MELODY_DATA:
    DB 7,0CH,4,0CH,4,4
	DB 5,0CH,2,0CH,2,2
	DB 0,2,4,5,7,0CH,7,0CH,7,7

INIT:
	MOV TMOD, #011H
	MOV IE, #10001010B   ; EA=1, ET1=1, ET0=1
	
	MOV P0, #00H
	MOV R0, #0CH ; 12 Frequenze For The Buzzer Buzz
	MOV R1, #00H ; Loop Count For The Buzzer Buzz In 1 Second For The Specific Frequence
	MOV R2, #00H ; Temp For TH1
	MOV R3, #00H ; Temp For TL1

	MOV R4, #00H  ;Index Of Melody Time Delay
	MOV R5, #00H  ;Index of Melody Data

	MOV  TH0, #0FFH
	MOV  TL0, #0FFH	
	MOV  TH1, #0FFH
	MOV  TL1, #0FFH
	SETB TR0
	SETB TR1

LOOP:
	JMP $

BUZZER_CHOOSE_FREQ:
BUZZER_D0:
	CJNE R0, #00H, BUZZER_D0_
		MOV R2, #0FCH
		MOV R3, #08FH
		RET

BUZZER_D0_:
	CJNE R0, #01H, BUZZER_RE
		MOV R2, #0FCH
		MOV R3, #0C0H
		RET

BUZZER_RE:
	CJNE R0, #02H, BUZZER_RE_
		MOV R2, #0FCH
		MOV R3, #0EFH
		RET

BUZZER_RE_:
	CJNE R0, #03H, BUZZER_MI
		MOV R2,	#0FDH
		MOV R3, #01BH
		RET

BUZZER_MI:
	CJNE R0, #04H, BUZZER_FA
		MOV R2, #0FDH
		MOV R3, #045H
		RET

BUZZER_FA:
	CJNE R0, #05H, BUZZER_FA_
		MOV R2, #0FDH
		MOV R3, #06CH
		RET

BUZZER_FA_:
	CJNE R0, #06H, BUZZER_SO
		MOV R2, #0FDH
		MOV R3, #091H
		RET

BUZZER_SO:
	CJNE R0, #07H, BUZZER_SO_
		MOV R2, #0FDH
		MOV R3, #0B4H
		RET

BUZZER_SO_:
	CJNE R0, #08H, BUZZER_LA
		MOV R2, #0FDH
		MOV R3, #0D5H
		RET

BUZZER_LA:
	CJNE R0, #09H, BUZZER_LA_
		MOV R2, #0FDH
		MOV R3, #0F4H
		RET

BUZZER_LA_:
	CJNE R0, #0AH, BUZZER_SI
		MOV R2, #0FEH
		MOV R3, #012H
		RET

BUZZER_SI:
	CJNE R0, #0BH, BUZZER_NON
		MOV R2, #0FEH
		MOV R3, #02EH
		RET

BUZZER_NON:
	CJNE R0, #0CH, DEFAULT
		MOV R2, #00H
		MOV R3, #00H
		RET

DEFAULT:
	MOV R2, #00H
	MOV R3, #00H
	RET

RESET_TIMER0:
	PUSH  ACC
	CLR   TR0

	MOV   DPTR, #RHYTHM_DATA
	MOV   A, R4
	MOVC  A, @A+DPTR
	MOV   TH0, A
	
	MOV   A, R4
	INC   A
	MOVC  A, @A+DPTR
	MOV   TL0, A

	CJNE  R1, #014H ,CONTINUE
	MOV   R1, #00H
	INC   R4
	INC   R4
	MOV   DPTR, #MELODY_DATA
	MOV   A, R5
	MOVC  A, @A+DPTR
	MOV   R0, A
	INC   R5
	ACALL BUZZER_CHOOSE_FREQ
	SETB  TR0
	POP   ACC
	RETI

CONTINUE:
	INC   R1
	SETB  TR0
	POP   ACC
	RETI

RESET_TIMER1:
	PUSH  ACC
	CLR   TR1
	MOV   TH1, R2
	MOV   TL1, R3
	CJNE  R2, #00H, PULSE
	CJNE  R3, #00H, PULSE
	MOV   P0,  #00H

PULSE:
	MOV   A, P0
	CPL   A
	MOV   P0, A
	SETB  TR1
	POP   ACC
	RETI
	END
