	ORG 00H
	AJMP INIT

	ORG 01BH
	AJMP RESET_TIMER1
	
	ORG 50H

KEYPAD:
	DB 00H
	DB 04H  
	DB 08H 
	DB 0CH  

	DB 01H  
	DB 05H  
	DB 09H   
	DB 0DH

	DB 02H  
	DB 06H  
	DB 0AH
	DB 0EH

	DB 03H   
	DB 07H  
	DB 0BH  
	DB 0FH

	DB 010H ; No key pressed

INIT:
	MOV TMOD, #011H
	MOV IE, #10001000B   ; EA=1, ET1=1
	MOV DPTR, #KEYPAD
    MOV R0, #00H ;Col Detection
	MOV R1, #00H  ;Row Detection
	MOV R2, #00H  ;Temp For Row Detection
	MOV R3, #00H  ;TH1
	MOV R4, #00H  ;TL1
	MOV P0, #00H  ;Buzzer Output
    MOV P1, #0FFH ;Keypad Input

LOOP:
	ACALL DETECT
	ACALL BUZZER_CHOOSE_FREQ
	JMP LOOP

DETECT:
	MOV R0, #010H
	MOV R1, #00H

DETECTCOL0:
    MOV P1, #07FH
	ACALL DELAY
	MOV A, P1
    ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
    JZ DETECTCOL1
	MOV R0, #00H
	ACALL DETECTROW
	RET

DETECTCOL1:
	MOV P1, #0BFH
	ACALL DELAY
	MOV A, P1
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DETECTCOL2
	MOV R0, #04H
	ACALL DETECTROW
	RET

DETECTCOL2:
	MOV P1, #0DFH
	ACALL DELAY
	MOV A, P1
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DETECTCOL3	
	MOV R0, #08H
	ACALL DETECTROW
	RET

DETECTCOL3:
	MOV P1, #0EFH
	ACALL DELAY
	MOV A, P1
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DEFAULT_NOPRESSED_COL
	MOV R0, #0CH
	ACALL DETECTROW
	RET

DEFAULT_NOPRESSED_COL:
	RET

DETECTROW:
	CJNE R2, #0EH,  NOTPRESSEDROW0
	MOV R1, #00H
	RET

NOTPRESSEDROW0:
	CJNE R2, #0DH,  NOTPRESSEDROW1
	MOV R1, #01H
	RET

NOTPRESSEDROW1:
	CJNE R2, #0BH,  NOTPRESSEDROW2
	MOV R1, #02H
	RET

NOTPRESSEDROW2:
	CJNE R2, #07H,  DEFAULT_NOPRESSED_ROW
	MOV R1, #03H
	RET

DEFAULT_NOPRESSED_ROW:
	RET

DELAY:
	MOV TH0, #0EFH
	MOV TL0, #0B9H
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET

;------------------------------------------------------------
BUZZER_CHOOSE_FREQ:
BUZZER_CHOOSE_FREQ_INIT:
	MOV A, R0
	ADD A, R1
	MOVC A, @A+DPTR

BUZZER_CHOOSE_FREQ_MAIN:
BUZZER_D0:
	CJNE A, #00H, BUZZER_D0_
		MOV R3, #0FCH
		MOV R4, #08FH
		SETB TR1
		RET

BUZZER_D0_:
	CJNE A, #04H, BUZZER_RE
		MOV R3, #0FCH
		MOV R4, #0C0H
		SETB TR1
		RET

BUZZER_RE:
	CJNE A, #08H, BUZZER_RE_
		MOV R3, #0FCH
		MOV R4, #0EFH
		SETB TR1
		RET

BUZZER_RE_:
	CJNE A, #0CH, BUZZER_MI
		MOV R3,	#0FDH
		MOV R4, #01BH
		SETB TR1
		RET

BUZZER_MI:
	CJNE A, #01H, BUZZER_FA
		MOV R3, #0FDH
		MOV R4, #045H
		SETB TR1
		RET

BUZZER_FA:
	CJNE A, #05H, BUZZER_FA_
		MOV R3, #0FDH
		MOV R4, #06CH
		SETB TR1
		RET

BUZZER_FA_:
	CJNE A, #09H, BUZZER_SO
		MOV R3, #0FDH
		MOV R4, #091H
		SETB TR1
		RET

BUZZER_SO:
	CJNE A, #0DH, BUZZER_SO_
		MOV R3, #0FDH
		MOV R4, #0B4H
		SETB TR1
		RET

BUZZER_SO_:
	CJNE A, #02H, BUZZER_LA
		MOV R3, #0FDH
		MOV R4, #0D5H
		SETB TR1
		RET

BUZZER_LA:
	CJNE A, #06H, BUZZER_LA_
		MOV R3, #0FDH
		MOV R4, #0F4H
		SETB TR1
		RET

BUZZER_LA_:
	CJNE A, #0AH, BUZZER_SI
		MOV R3, #0FEH
		MOV R4, #012H
		SETB TR1
		RET

BUZZER_SI:
	CJNE A, #0EH, DEFAULT_NOSOUND
		MOV R3, #0FEH
		MOV R4, #02EH
		SETB TR1
		RET

DEFAULT_NOSOUND:
	CLR TR1
	MOV P0, #00H
	RET

RESET_TIMER1:
	PUSH  ACC
	CLR   TR1
	MOV   TH1, R3
	MOV   TL1, R4
	MOV   A, P0
	CPL   A
	MOV   P0, A
	SETB  TR1
	POP   ACC
	RETI
	END
