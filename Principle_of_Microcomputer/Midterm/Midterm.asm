PAGE_LOBBY_STRING:
	DB "Select a Mode!"

ANIMATION_DATA:
	DB '.'
	DB 00H
	DB 01H
	DB 02H
	DB 03H

LCM_NUM:
	DB "0123456789"

KEYPAD_NUM:
	DB 00H
	DB 04H  
	DB 08H 
	DB 0CH  

	DB 01H  
	DB 05H  
	DB 09H   
	DB 0DH

	DB 02H  
	DB 06H  
	DB 0AH
	DB 0EH

	DB 03H   
	DB 07H  
	DB 0BH  
	DB 0FH

	DB 010H ; No key pressed

INIT:
    MOV TMOD, #01H 

    MOV R0, #010H ;Col Detection
	MOV R1, #00H  ;Row Detection
	MOV R2, #00H  ;Temp For Row Detection
    MOV KEYPAD_IO, #0FFH ;Keypad I/O

	MOV R3, #00H ;String Character Counter
	MOV R4, #0AH ;Number of Characters for Mode 1
	
	CLR LCD_RW
	ACALL DELAY10MS

	MOV A,#00111011B
	ACALL WRIR

	MOV A,#00001110B
	ACALL WRIR

	MOV A,#00000001B
	ACALL WRIR

	MOV A,#10000000B
	ACALL WRIR

	ACALL WRITE_CUSTOM_CHAR1
	ACALL WRITE_CUSTOM_CHAR2
	ACALL WRITE_CUSTOM_CHAR3
	ACALL WRITE_CUSTOM_CHAR4
	ACALL WRITE_CUSTOM_CHAR5

LOOP:
	ACALL MAIN
	JMP LOOP

MAIN:
;PAGE_LOBBY---------------------
PAGE_LOBBY:
	ACALL LCM_RESET
	MOV DPTR, #PAGE_LOBBY_STRING
	MOV R3, #0EH

PAGE_LOBBY_MAIN:
	CLR A
	MOVC A, @A+DPTR
	ACALL WRDR
	INC DPTR
	DJNZ R3, PAGE_LOBBY_MAIN

DETECT_MODE:
	ACALL KEYPAD_DETECT
	MOV A, R0
	ADD A, R1
	CJNE A, #010H, SELECT_PAGE
	JMP DETECT_MODE

SELECT_PAGE:
	MOV DPTR, #KEYPAD_NUM
	MOVC A, @A+DPTR

SELECT_PAGE1:
	CJNE A, #00H, SELECT_PAGE2
	ACALL PAGE_1
	RET

SELECT_PAGE2:
	CJNE A, #01H, SELECT_PAGE3
	ACALL PAGE_2
	RET

SELECT_PAGE3:
	CJNE A, #02H, DETECT_MODE
	ACALL PAGE_3
	RET

;MODE---------------------------
PAGE_1:
	ACALL LCM_RESET
	MOV A, #0C0H
	ACALL WRIR
	MOV R4, #0AH

PAGE_1_MAIN:
	ACALL KEYPAD_DETECT
	MOV A, R0
	ADD A, R1
	MOV DPTR, #KEYPAD_NUM
	MOVC A, @A+DPTR
	CJNE A, #0FH, SELECT_NUM
	RET

SELECT_NUM:
	CJNE R4, #00H, SELECT_NUM0
	JMP SHIFT_NUM

SELECT_NUM0:
	CJNE A, #07H, SELECT_NUM1
	MOV DPTR, #LCM_NUM
	MOV  A, #00H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM1:
	CJNE A, #04H, SELECT_NUM2
	MOV DPTR, #LCM_NUM
	MOV  A, #01H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM2:
	CJNE A, #05H, SELECT_NUM3
	MOV DPTR, #LCM_NUM
	MOV  A, #02H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM3:
	CJNE A, #06H, SELECT_NUM4
	MOV DPTR, #LCM_NUM
	MOV  A, #03H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM4:
	CJNE A, #08H, SELECT_NUM5
	MOV DPTR, #LCM_NUM
	MOV  A, #04H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM5:
	CJNE A, #09H, SELECT_NUM6
	MOV DPTR, #LCM_NUM
	MOV  A, #05H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM6:
	CJNE A, #0AH, SELECT_NUM7
	MOV DPTR, #LCM_NUM
	MOV  A, #06H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM7:
	CJNE A, #0CH, SELECT_NUM8
	MOV DPTR, #LCM_NUM
	MOV  A, #07H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM8:
	CJNE A, #0DH, SELECT_NUM9
	MOV DPTR, #LCM_NUM
	MOV  A, #08H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SELECT_NUM9:
	CJNE A, #0EH, SHIFT_NUM
	MOV DPTR, #LCM_NUM
	MOV  A, #09H
	MOVC A, @A+DPTR
	ACALL WRDR
	DEC R4
	ACALL DELAY200MS
	JMP PAGE_1_MAIN

SHIFT_NUM:
	CJNE A, #0BH, SHIFT_JUMP
	JMP SHIFT_NUM1

SHIFT_JUMP:
	AJMP PAGE_1_MAIN

SHIFT_NUM1:
	ACALL KEYPAD_DETECT
	MOV A, R0
	ADD A, R1
	MOV DPTR, #KEYPAD_NUM
	MOVC A, @A+DPTR
	CJNE A, #0FH, SHIFT_NUM2
	RET	

SHIFT_NUM2:
	MOV A, #00011100B
	ACALL WRIR
	ACALL DELAY200MS
	ACALL DELAY200MS
	JMP SHIFT_NUM1

PAGE_2:
	MOV R6, #080H

PAGE_2_MAIN:
	ACALL KEYPAD_DETECT
	MOV A, R0
	ADD A, R1
	MOV DPTR, #KEYPAD_NUM
	MOVC A, @A+DPTR
	CJNE A, #0FH, ANIMATION
	RET

ANIMATION:
SHIFT_ANIMATION_LINE:
	CJNE R6, #08FH, CHECK_ANIMATION_END
	MOV R6, #0C0H
	JMP CHECK_ANIMATION_END

CHECK_ANIMATION_END:
	CJNE R6, #0CFH, RUN_ANIMATION
	MOV R6, #080H

RUN_ANIMATION:
	MOV R5, #03H

RUN_ANIMATION_MAIN:
	ACALL LCM_RESET
	MOV A, R6
	ACALL WRIR
	MOV DPTR, #ANIMATION_DATA
	MOV A, R5
	MOVC A, @A+DPTR
	ACALL WRDR
	ACALL DRAW_DOT
	DJNZ R5, RUN_ANIMATION_MAIN
	INC R6
	ACALL DELAY200MS
	JMP PAGE_2_MAIN

DRAW_DOT:
	MOV A, R6
	MOV R7, A
	INC R7

CHANGE_DOT_LINE:
	CJNE R7, #08FH, DRAW_DOT_END
	MOV R7, #0C0H
	JMP DRAW_DOT_MAIN

DRAW_DOT_END:
	CJNE R7, #0CFH, DRAW_DOT_MAIN
	RET

DRAW_DOT_MAIN:
	MOV A, R7
	ACALL WRIR
	MOV A, #04H
	MOVC A, @A+DPTR
	ACALL WRDR
	INC R7
	JMP CHANGE_DOT_LINE

PAGE_3:
PAGE_3_MAIN:
	ACALL LCM_RESET
	MOV R7, #010H
	MOV R6, #080H

PAGE_3_PRINT_NULL1:
	MOV A, R6
	ACALL WRIR
	MOV A, #04H
	ACALL WRDR
	INC R6
	DJNZ R7, PAGE_3_PRINT_NULL1
	
	MOV R7, #010H
	MOV R6, #0C0H

PAGE_3_PRINT_NULL2:
	MOV A, R6
	ACALL WRIR
	MOV A, #04H
	ACALL WRDR
	INC R6
	DJNZ R7, PAGE_3_PRINT_NULL2

PAGE_3_RETURN:
	ACALL KEYPAD_DETECT
	MOV A, R0
	ADD A, R1
	MOV DPTR, #KEYPAD_NUM
	MOVC A, @A+DPTR
	CJNE A, #0FH, PAGE_3_RETURN
	RET

;LCM----------------------------
LCM_RESET:
	MOV A,#00000001B
	ACALL WRIR
	RET

WRIR:
	MOV LCD_DATA, A
	CLR LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

WRDR:
	MOV LCD_DATA, A
	SETB LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

