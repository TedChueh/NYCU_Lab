LCD_EN EQU  P3.0
LCD_RW EQU  P3.1
LCD_RS EQU  P3.2
LCD_DATA EQU P0
KEYPAD_IO EQU P1	
	
	ORG 00H
	AJMP INIT
	ORG 50H

