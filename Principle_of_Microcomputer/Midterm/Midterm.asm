DELAY200MS:
	MOV R7, #20
DELAY200MS_MAIN:
	ACALL DELAY10MS
	DJNZ R7, DELAY200MS_MAIN
	RET

DELAY10MS:
	MOV TH0, #0D8H   
	MOV TL0, #0F0H   
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET

;KEYPAD-------------------------
KEYPAD_DETECT:
	MOV R0, #010H
	MOV R1, #00H

DETECTCOL0:
    MOV KEYPAD_IO, #07FH
	ACALL DELAY4MS
	MOV A, KEYPAD_IO
    ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
    JZ DETECTCOL1
	MOV R0, #00H
	ACALL DETECTROW
	RET

DETECTCOL1:
	MOV KEYPAD_IO, #0BFH
	ACALL DELAY4MS
	MOV A, KEYPAD_IO
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DETECTCOL2
	MOV R0, #04H
	ACALL DETECTROW
	RET

DETECTCOL2:
	MOV KEYPAD_IO, #0DFH
	ACALL DELAY4MS
	MOV A, KEYPAD_IO
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DETECTCOL3	
	MOV R0, #08H
	ACALL DETECTROW
	RET

DETECTCOL3:
	MOV KEYPAD_IO, #0EFH
	ACALL DELAY4MS
	MOV A, KEYPAD_IO
	ANL A, #0FH
	MOV R2, A
	CLR C
	SUBB A, #0FH
	JZ DEFAULT_NOPRESSED
	MOV R0, #0CH
	ACALL DETECTROW
	RET

DEFAULT_NOPRESSED:
	RET

DETECTROW:
	CJNE R2, #0EH,  NOTPRESSEDROW0
	MOV R1, #00H
	RET

NOTPRESSEDROW0:
	CJNE R2, #0DH,  NOTPRESSEDROW1
	MOV R1, #01H
	RET

NOTPRESSEDROW1:
	CJNE R2, #0BH,  NOTPRESSEDROW2
	MOV R1, #02H
	RET

NOTPRESSEDROW2:
	CJNE R2, #07H,  DEFAULT
	MOV R1, #03H
	RET

DEFAULT:
	RET
	
DELAY4MS:
	MOV TH0, #0F0H
	MOV TL0, #060H
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET
