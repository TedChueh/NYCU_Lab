LCD_EN EQU  P0.0
LCD_RW EQU  P0.1
LCD_RS EQU  P0.2
LCD_DATA EQU P1	
	
	ORG 00H
	AJMP INIT
	ORG 50H

CUSTOM_CHAR1:
  	DB 00H
  	DB 00H
  	DB 03H
  	DB 013H
  	DB 0EH
  	DB 0AH
  	DB 00H
	DB 00H

CUSTOM_CHAR2:
  	DB 00H
  	DB 00H
  	DB 03H
  	DB 013H
  	DB 0EH
  	DB 011H
  	DB 00H
	DB 00H

INIT:
	MOV TMOD, #01H
	CLR LCD_RW
	ACALL DELAY10MS

	MOV A,#00111011B
	ACALL WRIR

	MOV A,#00001110B
	ACALL WRIR

	MOV A,#00000001B
	ACALL WRIR

	MOV A,#10000000B
	ACALL WRIR

	ACALL WRITE_CUSTOM_CHAR1
	ACALL WRITE_CUSTOM_CHAR2

	MOV A, #080H
	ACALL WRIR

LOOP:
	MOV  A, #00H
	ACALL WRDR
	ACALL DELAY200MS
	ACALL LCM_RESET

	MOV  A, #01H
	ACALL WRDR
	ACALL DELAY200MS
	ACALL LCM_RESET

	JMP LOOP

LCM_RESET:
	MOV A,#10000000B
	ACALL WRIR
	RET

WRITE_CUSTOM_CHAR1:
WRITE_CUSTOM_CHAR1_INIT:
	MOV A, #040H
	ACALL WRIR
	MOV DPTR, #CUSTOM_CHAR1
	MOV R0, #08H
WRITE_CUSTOM_CHAR1_MAIN:
	MOV  A, #00H
	MOVC A, @A+DPTR
	ACALL WRDR
	INC DPTR
	DJNZ R0, WRITE_CUSTOM_CHAR1_MAIN
	RET

WRITE_CUSTOM_CHAR2:
WRITE_CUSTOM_CHAR2_INIT:
	MOV A, #048H
	ACALL WRIR
	MOV DPTR, #CUSTOM_CHAR2
	MOV R0, #08H
WRITE_CUSTOM_CHAR2_MAIN:
	MOV  A, #00H
	MOVC A, @A+DPTR
	ACALL WRDR
	INC DPTR
	DJNZ R0, WRITE_CUSTOM_CHAR2_MAIN
	RET	

WRIR:
	MOV LCD_DATA, A
	CLR LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

WRDR:
	MOV LCD_DATA, A
	SETB LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

DELAY200MS:
DELAY200MS_INIT:
	MOV R1, #20
DELAY200MS_MAIN:
	ACALL DELAY10MS
	DJNZ R1, DELAY200MS_MAIN
	RET

DELAY10MS:
	MOV TH0, #0D8H   
	MOV TL0, #0F0H   
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET
	END
