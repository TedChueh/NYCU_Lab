LCD_EN EQU  P0.0
LCD_RW EQU  P0.1
LCD_RS EQU  P0.2
LCD_DATA EQU P1	
	
	ORG 00H
	AJMP INIT
	ORG 50H

STUDENTID_ASCII:
	DB '1' ;1
	DB '1' ;1
	DB '3' ;3
	DB '5' ;5
	DB '1' ;1
	DB '1' ;1
	DB '0' ;0
	DB '8' ;8
	DB '4' ;4

INIT:
	MOV TMOD, #01H
	MOV DPTR, #STUDENTID_ASCII
	CLR LCD_RW
	ACALL DELAY10MS

	MOV A,#00111011B
	ACALL WRIR

	MOV A,#00001110B
	ACALL WRIR

	MOV A,#00000001B
	ACALL WRIR

	MOV A,#10000000B
	ACALL WRIR

	MOV R0, #09H

LOOP:
	MOV  A, #00H
	MOVC A, @A+DPTR
	ACALL WRDR
	INC DPTR
	DJNZ R0, LOOP
	SJMP $

WRIR:
	MOV LCD_DATA, A
	CLR LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

WRDR:
	MOV LCD_DATA, A
	SETB LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

DELAY10MS:
	MOV TH0, #0D8H   
	MOV TL0, #0F0H   
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET
	END
