LCD_EN EQU  P3.0
LCD_RW EQU  P3.1
LCD_RS EQU  P3.2
LCD_DATA EQU P0
	
	ORG 00H
	AJMP INIT
	ORG 50H


INIT:
	MOV TMOD, #01H
	CLR LCD_RW
	ACALL DELAY10MS

	MOV A,#00111011B
	ACALL WRIR

	MOV A,#00001110B
	ACALL WRIR

	MOV A,#00000001B
	ACALL WRIR

	MOV A,#10000000B
	ACALL WRIR

LOOP:
	ACALL DOTCIRCLING
	JMP LOOP

DOTCIRCLING:
DOTCIRCLING1_INIT:
	MOV R0, #080H
	MOV R1, #010H
DOTCIRCLING1_MAIN:
	ACALL LCM_RESET
	MOV A, R0
	ACALL WRIR
	MOV A, #02EH
	ACALL WRDR
	ACALL DELAY200MS
	INC R0
	DJNZ R1, DOTCIRCLING1_MAIN
DOTCIRCLING2_INIT:
	MOV R0, #0CFH
	MOV R1, #010H
DOTCIRCLING2_MAIN:
	ACALL LCM_RESET
	MOV A, R0
	ACALL WRIR
	MOV A, #02EH
	ACALL WRDR
	ACALL DELAY200MS
	DEC R0
	DJNZ R1, DOTCIRCLING2_MAIN
	RET

LCM_RESET:
	MOV A,#00000001B
	ACALL WRIR
	RET

WRIR:
	MOV LCD_DATA, A
	CLR LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

WRDR:
	MOV LCD_DATA, A
	SETB LCD_RS
	SETB LCD_EN
	ACALL DELAY10MS
	CLR LCD_EN
	ACALL DELAY10MS
	RET

DELAY200MS:
DELAY200MS_INIT:
	MOV R7, #20
DELAY200MS_MAIN:
	ACALL DELAY10MS
	DJNZ R7, DELAY200MS_MAIN
	RET

DELAY10MS:
	MOV TH0, #0D8H   
	MOV TL0, #0F0H   
	SETB TR0	
	JNB TF0, $
	CLR TR0
	CLR TF0
	RET
	END
